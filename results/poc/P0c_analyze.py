"""P0c throwaway analyzer: reads the laya-evals report JSONs (`cases[*]`) and the build meta, and
writes results/poc/P0c_analysis.md. No model forward pass; the head-budget section loads only the
checkpoint tokenizers.

    source env.sh && .venv/bin/python results/poc/P0c_analyze.py
"""
import json
import math
import re
import statistics
from collections import Counter
from pathlib import Path

import numpy as np
from laya.agent import _load_tokenizer
from laya.common import build_head, encode_text, render_options

R = Path(__file__).resolve().parent
ROOT = R.parent.parent
META = json.loads((R / "P0c_build_meta.json").read_text(encoding="utf-8"))
SETS = {"ynat100": ("P0c_ynat100", "topic"), "massive-scenario18": ("P0c_massive_scenario18_100", "scenario")}
VARIANTS = {"base": "", "ko-instr": "_ko-instr", "en-desc": "_en-desc", "ko-instr_en-desc": "_ko-instr_en-desc"}
LANGS = {"base": "en / ko", "ko-instr": "ko / ko", "en-desc": "en / en", "ko-instr_en-desc": "ko / en"}
RUNS = [(s, v, "multilingual") for s in SETS for v in VARIANTS] + [(s, "base", "english") for s in SETS]
CKPT_DIRS = {"multilingual": ROOT / "models/laya-multilingual", "english": ROOT / "models/laya"}


def wilson(x, n, z=1.96):
    p = x / n
    centre = (p + z * z / (2 * n)) / (1 + z * z / n)
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / (1 + z * z / n)
    return centre - half, centre + half


def mcnemar_exact(b, c):
    n = b + c
    if n == 0:
        return 1.0
    return min(1.0, 2 * sum(math.comb(n, i) for i in range(min(b, c) + 1)) / 2 ** n)


def macro_f1(gold, pred, labels):
    f1s = []
    for lab in labels:
        tp = sum(g == lab and p == lab for g, p in zip(gold, pred))
        fp = sum(g != lab and p == lab for g, p in zip(gold, pred))
        fn = sum(g == lab and p != lab for g, p in zip(gold, pred))
        prec = tp / (tp + fp) if tp + fp else 0.0
        rec = tp / (tp + fn) if tp + fn else 0.0
        f1s.append(2 * prec * rec / (prec + rec) if prec + rec else 0.0)
    return sum(f1s) / len(f1s)


def load_run(s, v, m):
    stem, qid = SETS[s]
    jsonl = "%s%s.jsonl" % (stem, VARIANTS[v])
    rep = json.loads((R / ("P0c_%s_%s_%s.json" % (s, v, m))).read_text(encoding="utf-8"))
    cases = [c for c in rep["cases"] if c["qid"] == qid]
    assert len(cases) == 100, len(cases)
    meta = META["files"][jsonl]
    cfg = rep["config"]
    # run identity: the report's own hashes must match what the builder recorded
    assert cfg["dataset_sha256"] == meta["sha256"], (jsonl, cfg["dataset_sha256"])
    assert cfg["questions_sha256"] == meta["questions_sha256"], (jsonl, cfg["questions_sha256"])
    gold = [c["expected"] for c in cases]
    pred = [c["answer"]["choice"] for c in cases]
    correct = [c["correct"] for c in cases]
    assert correct == [g == p for g, p in zip(gold, pred)]
    acc = sum(correct) / 100
    assert abs(acc - rep["overall"]["choice_accuracy"]) < 1e-12, (acc, rep["overall"]["choice_accuracy"])
    conf = [c["answer"]["answer_confidence"] for c in cases]
    return {"set": s, "variant": v, "model": m, "jsonl": jsonl, "cfg": cfg, "overall": rep["overall"],
            "gold": gold, "pred": pred, "correct": correct, "conf": conf,
            "options": list(json.loads(next(l for l in (R / jsonl).read_text(encoding="utf-8").splitlines()
                                            if l.startswith("{")))["questions"][qid]["criteria"])}


def fmt(x, d=3):
    return "-" if x is None else ("%.*f" % (d, x))


def main():
    runs = {(s, v, m): load_run(s, v, m) for s, v, m in RUNS}
    out = ["# P0c analysis (generated by results/poc/P0c_analyze.py)", ""]

    out += ["## 1. Summary (n=100 per run; 95% Wilson CI; ECE and mean_confidence as reported)", "",
            "| set | variant (instr / desc) | model | accuracy (x/100) | 95% CI | macro-F1 (gold∪pred) | macro-F1 (gold labels) "
            "| mean answer_confidence | ECE | acc@50%cov | majority | random 1/k | acc - majority |",
            "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for (s, v, m), r in runs.items():
        x = sum(r["correct"])
        lo, hi = wilson(x, 100)
        gold_labels = sorted(set(r["gold"]))
        union = sorted(set(r["gold"]) | set(r["pred"]))
        maj = max(Counter(r["gold"]).values()) / 100
        c = np.asarray(r["conf"])
        # same expression as research/scripts/bench_local.py:148
        acc50 = float(np.asarray(r["correct"], dtype=float)[np.argsort(-c)[:max(1, len(c) // 2)]].mean())
        out.append("| %s | %s (%s) | %s | %.2f (%d/100) | %.2f-%.2f | %.3f | %.3f | %.3f | %.3f | %.2f | %.2f | %.3f | %+.2f |" % (
            s, v, LANGS[v], m, x / 100, x, lo, hi, macro_f1(r["gold"], r["pred"], union),
            macro_f1(r["gold"], r["pred"], gold_labels), statistics.fmean(r["conf"]),
            r["overall"]["ece"], acc50, maj, 1 / len(r["options"]), x / 100 - maj))
        assert abs(statistics.fmean(r["conf"]) - r["overall"]["mean_confidence"]) < 1e-9

    out += ["", "## 2. Paired comparisons on the same 100 rows (exact two-sided McNemar)", "",
            "b = only A correct, c = only B correct.", "",
            "| set | A | B | acc A | acc B | Δ (B-A) | b | c | p | argmax agreement A vs B |", "|---|---|---|---|---|---|---|---|---|---|"]
    pairs = [((s, "base", "multilingual"), (s, v, "multilingual")) for s in SETS for v in VARIANTS if v != "base"]
    pairs += [((s, "en-desc", "multilingual"), (s, "ko-instr_en-desc", "multilingual")) for s in SETS]
    pairs += [((s, "ko-instr", "multilingual"), (s, "ko-instr_en-desc", "multilingual")) for s in SETS]
    pairs += [((s, "base", "english"), (s, "base", "multilingual")) for s in SETS]
    for a, b in pairs:
        ra, rb = runs[a], runs[b]
        nb = sum(x and not y for x, y in zip(ra["correct"], rb["correct"]))
        nc = sum(y and not x for x, y in zip(ra["correct"], rb["correct"]))
        agree = sum(p == q for p, q in zip(ra["pred"], rb["pred"]))
        out.append("| %s | %s/%s | %s/%s | %.2f | %.2f | %+.2f | %d | %d | %.3f | %d/100 |" % (
            a[0], a[1], a[2], b[1], b[2], sum(ra["correct"]) / 100, sum(rb["correct"]) / 100,
            (sum(rb["correct"]) - sum(ra["correct"])) / 100, nb, nc, mcnemar_exact(nb, nc), agree))

    for s in SETS:
        keys = runs[(s, "base", "multilingual")]["options"]
        cols = [k for k in runs if k[0] == s]
        gold_count = Counter(runs[cols[0]]["gold"])
        out += ["", "## 3. %s: per-gold-label recall (correct / gold rows)" % s, "",
                "| gold label | n | " + " | ".join("%s/%s" % (v, m) for _, v, m in cols) + " |",
                "|---|---|" + "---|" * len(cols)]
        for k in keys:
            if not gold_count[k]:
                continue
            cells = []
            for c in cols:
                r = runs[c]
                tp = sum(g == k and p == k for g, p in zip(r["gold"], r["pred"]))
                cells.append("%d/%d" % (tp, gold_count[k]))
            out.append("| %s | %d | %s |" % (k, gold_count[k], " | ".join(cells)))
        out += ["", "Prediction distribution (count of each predicted label; labels never predicted omitted):", "",
                "| run | predicted label counts |", "|---|---|"]
        for c in cols:
            pc = Counter(runs[c]["pred"])
            out.append("| %s/%s | %s |" % (c[1], c[2], ", ".join("%s %d" % kv for kv in pc.most_common())))
        out += ["", "Top confusions (gold → predicted, count):", "", "| run | top 6 confusions |", "|---|---|"]
        for c in cols:
            conf = Counter((g, p) for g, p in zip(runs[c]["gold"], runs[c]["pred"]) if g != p)
            out.append("| %s/%s | %s |" % (c[1], c[2], ", ".join("%s→%s %d" % (g, p, n) for (g, p), n in conf.most_common(6))))

    out += ["", "## 4. Head token budget per file × checkpoint (laya.common.build_head, tokenizer only)", "",
            "Option text = `key: description`. raw = [MASK] + option tokens before the per-option cap; cap = "
            "max(4, (head_max_len-16)//k) applied only when the options overflow head_max_len-16.", "",
            "| file | ckpt (head_max_len) | k | raw tokens/option min-median-max | cap | options cut | distinct | "
            "instruction tokens kept/raw | longest option as kept (decoded) |", "|---|---|---|---|---|---|---|---|---|"]
    toks = {}
    for m, d in CKPT_DIRS.items():
        cfg = json.loads((d / "rl_agent_config.json").read_text(encoding="utf-8"))
        toks[m] = (_load_tokenizer(str(d / "tokenizer"), cfg), cfg["head_max_len"])
    for (s, v, m), r in runs.items():
        tok, hml = toks[m]
        q = json.loads(next(l for l in (R / r["jsonl"]).read_text(encoding="utf-8").splitlines() if l.startswith("{")))
        qd = q["questions"][SETS[s][1]]
        iq = {"t": "choice", "ins": qd["instructions"], "crit": qd["criteria"]}
        ids, markers, stats = build_head(tok, iq, hml)
        opts = render_options(iq)
        raw = [1 + len(encode_text(tok, " " + o, add_special_tokens=False, truncation=True, max_length=48)["input_ids"])
               for o in opts]
        cap = stats["tokens_per_option"]
        ins_raw = len(encode_text(tok, "choice question: %s" % qd["instructions"], add_special_tokens=False)["input_ids"])
        ins_kept = markers[0] - 2
        longest = max(range(len(opts)), key=lambda i: raw[i])
        end = markers[longest + 1] if longest + 1 < len(markers) else len(ids) - 1
        kept_text = tok.decode(ids[markers[longest] + 1:end]).strip()
        out.append("| %s | %s (%d) | %d | %d-%d-%d | %s | %d | %d/%d | %d/%d | `%s` |" % (
            r["jsonl"], m, hml, len(opts), min(raw), int(statistics.median(raw)), max(raw), cap if cap else "none",
            sum(x > cap for x in raw) if cap else 0, stats["options_distinct"], stats["options"], ins_kept, ins_raw,
            kept_text.replace("|", "\\|")))

    out += ["", "## 5. Report identity and warnings (verbatim, deduplicated per log)", "",
            "| run | dataset_sha256 | questions_sha256 | revisions | timing (batch_form, chunks, rows_grouped) |",
            "|---|---|---|---|---|"]
    for (s, v, m), r in runs.items():
        cfg = r["cfg"]
        t = cfg["timing"]
        out.append("| %s/%s/%s | %s | %s | %s | %s, %s, %s |" % (
            s, v, m, cfg["dataset_sha256"], cfg["questions_sha256"], json.dumps(cfg["revisions"]),
            t["batch_form"], t["chunks"], t["rows_grouped"]))
    out.append("")
    for (s, v, m) in runs:
        log = (R / ("P0c_%s_%s_%s.log" % (s, v, m))).read_text(encoding="utf-8")
        warn = list(dict.fromkeys(l.strip() for l in re.split(r"[\r\n]", log) if "Warning" in l or "warning" in l))
        out.append("- P0c_%s_%s_%s.log: %s" % (s, v, m, " / ".join("`%s`" % w for w in warn) if warn else "no warning lines"))
    (R / "P0c_analysis.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
